//! Contract tests of the IPC. Every command is a line of `src-tauri/commands.txt`: `build.rs`
//! builds the app manifest and the capability of the main window from it, this test writes the
//! TypeScript command map (`ui/src/lib/ipc/types/commands.ts`) from it and checks it against
//! `generate_handler!` (`src-tauri/src/commands/mod.rs`) both ways - a command missing on
//! one side would otherwise only show at runtime ("command not allowed" or not found). Each
//! handler's parameters, as the page names them, and its result agree with the table too. The
//! types the map names are generated by `core/src/view/ts.rs`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn repo(relative: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join(relative)
}

fn read(relative: &str) -> String {
    std::fs::read_to_string(repo(relative)).unwrap_or_else(|e| panic!("{relative}: {e}"))
}

/// The text between `start` and the next `end`.
fn between<'a>(text: &'a str, start: &str, end: &str) -> &'a str {
    let from = text.find(start).unwrap_or_else(|| panic!("{start}")) + start.len();
    let to = from + text[from..].find(end).unwrap_or_else(|| panic!("{end}"));
    &text[from..to]
}

/// `(name, arguments, result)` of every command of `src-tauri/commands.txt` (`{}` = no
/// arguments), in its order.
fn command_table() -> Vec<(String, String, String)> {
    read("src-tauri/commands.txt")
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| {
            let (name, rest) = line.split_once(char::is_whitespace).unwrap_or((line, ""));
            let (args, result) = rest
                .rsplit_once(" -> ")
                .unwrap_or_else(|| panic!("commands.txt: no result in {line:?}"));
            let args = match args.trim() {
                "{}" => "Record<string, never>",
                args => args,
            };
            (name.to_owned(), args.to_owned(), result.trim().to_owned())
        })
        .collect()
}

/// The entries of `generate_handler!`, by their function name, in their order.
fn handler_names() -> Vec<String> {
    let source = read("src-tauri/src/commands/mod.rs");
    between(&source, "generate_handler![", "]")
        .split(',')
        .map(str::trim)
        .filter(|entry| !entry.is_empty())
        .map(|entry| entry.rsplit("::").next().unwrap().to_string())
        .collect()
}

/// The parameters Tauri fills in itself: the page never sends them.
const INJECTED: [&str; 5] = ["AppHandle", "State", "Webview", "WebviewWindow", "Window"];

/// A handler of `src-tauri/src/commands/`: its parameters as the page names them (camelCase,
/// the injected ones left out) with their TypeScript type, and its result in TypeScript.
#[derive(Debug)]
struct Handler {
    params: BTreeMap<String, String>,
    result: String,
}

/// The index of the bracket that closes the one at `open`.
fn closing(text: &str, open: usize) -> usize {
    let mut depth = 0usize;
    for (i, c) in text.char_indices().skip_while(|(i, _)| *i < open) {
        match c {
            '(' | '<' | '[' => depth += 1,
            ')' | '>' | ']' => {
                depth -= 1;
                if depth == 0 {
                    return i;
                }
            }
            _ => {}
        }
    }
    panic!("unclosed bracket in {text:.80}")
}

/// `text` split at its commas outside brackets, each part trimmed, empty ones left out.
fn top_level(text: &str) -> Vec<&str> {
    let (mut parts, mut depth, mut from) = (Vec::new(), 0usize, 0);
    for (i, c) in text.char_indices() {
        match c {
            '(' | '<' | '[' => depth += 1,
            ')' | '>' | ']' => depth -= 1,
            ',' if depth == 0 => {
                parts.push(text[from..i].trim());
                from = i + 1;
            }
            _ => {}
        }
    }
    parts.push(text[from..].trim());
    parts.retain(|part| !part.is_empty());
    parts
}

/// The last segment of a path (`view::AppState` is `AppState`).
fn last_segment(path: &str) -> &str {
    path.rsplit("::").next().unwrap().trim()
}

/// A Rust type of a handler as the TypeScript of the table writes it.
fn typescript(rust: &str) -> String {
    let rust = rust.trim().trim_start_matches('&').trim();
    if rust == "()" {
        return "null".to_owned();
    }
    if let Some(open) = rust.find('<') {
        let outer = last_segment(&rust[..open]);
        let inner = top_level(&rust[open + 1..closing(rust, open)]);
        return match outer {
            "Option" => format!("{} | null", typescript(inner[0])),
            "Vec" => format!("{}[]", typescript(inner[0])),
            "CmdResult" | "Result" => typescript(inner[0]),
            _ => format!("{outer}<{}>", typescript(inner[0])),
        };
    }
    match last_segment(rust) {
        "String" | "str" => "string".to_owned(),
        "bool" => "boolean".to_owned(),
        "u8" | "u16" | "u32" | "u64" | "usize" | "i8" | "i16" | "i32" | "i64" | "isize" | "f32"
        | "f64" => "number".to_owned(),
        other => other.to_owned(),
    }
}

/// `snake_case` as `camelCase`, the names Tauri reads the arguments by.
fn camel(snake: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in snake.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// Every `#[tauri::command]` fn of `src-tauri/src/commands/`, by its name.
fn handlers() -> BTreeMap<String, Handler> {
    const ATTRIBUTE: &str = "#[tauri::command]";
    let mut out = BTreeMap::new();
    for entry in std::fs::read_dir(repo("src-tauri/src/commands")).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_none_or(|e| e != "rs") {
            continue;
        }
        let source = std::fs::read_to_string(&path).unwrap();
        let mut rest = source.as_str();
        while let Some(at) = rest.find(ATTRIBUTE) {
            rest = &rest[at + ATTRIBUTE.len()..];
            let signature = &rest[rest.find("fn ").expect("fn after the attribute") + 3..];
            let open = signature.find('(').unwrap();
            let name = signature[..open]
                .split('<')
                .next()
                .unwrap()
                .trim()
                .to_owned();
            let close = closing(signature, open);
            let mut params = BTreeMap::new();
            for param in top_level(&signature[open + 1..close]) {
                let (ident, ty) = param.split_once(':').unwrap_or_else(|| panic!("{param}"));
                let base = last_segment(ty.split('<').next().unwrap());
                if !INJECTED.contains(&base) {
                    let ident = ident.trim().trim_start_matches("mut ").trim();
                    params.insert(camel(ident), typescript(ty));
                }
            }
            let tail = &signature[close + 1..];
            let result = tail[..tail.find('{').unwrap()]
                .trim()
                .strip_prefix("->")
                .map_or_else(|| "null".to_owned(), typescript);
            out.insert(name, Handler { params, result });
        }
    }
    out
}

/// The arguments of a line of the table, by name: `{ to: Place; keys: JobKey[] }`.
fn table_params(args: &str) -> BTreeMap<String, String> {
    if args == "Record<string, never>" {
        return BTreeMap::new();
    }
    args.trim()
        .trim_start_matches('{')
        .trim_end_matches('}')
        .split(';')
        .map(str::trim)
        .filter(|arg| !arg.is_empty())
        .map(|arg| {
            let (name, ts) = arg.split_once(':').unwrap_or_else(|| panic!("{arg}"));
            (name.trim().to_owned(), ts.trim().to_owned())
        })
        .collect()
}

/// A type without its spaces, so the table's layout does not count.
fn squashed(ts: &str) -> String {
    ts.chars().filter(|c| !c.is_whitespace()).collect()
}

/// The TypeScript command map for the table.
fn commands_ts(table: &[(String, String, String)]) -> String {
    let types: BTreeSet<String> = std::fs::read_dir(repo("ui/src/lib/ipc/types"))
        .expect("generated types (cargo test -p jobalert-core ipc_types)")
        .filter_map(|e| {
            let name = e.ok()?.file_name().to_string_lossy().into_owned();
            let module = name.strip_suffix(".ts")?.to_string();
            (module != "index" && module != "commands").then_some(module)
        })
        .collect();
    let used: BTreeSet<&String> = types
        .iter()
        .filter(|t| {
            table.iter().any(|(_, args, result)| {
                format!("{args} {result}")
                    .split(|c: char| !c.is_ascii_alphanumeric())
                    .any(|word| word == t.as_str())
            })
        })
        .collect();
    let mut out = String::from(
        "// Generated by core/tests/contract.rs from src-tauri/commands.txt. Do not edit.\n\
         import type { Channel } from \"@tauri-apps/api/core\";\n",
    );
    for t in &used {
        let _ = writeln!(out, "import type {{ {t} }} from \"./{t}\";");
    }
    out.push_str(
        "\n/** Every IPC command: its arguments and its result. */\nexport type Commands = {\n",
    );
    for (name, args, result) in table {
        let _ = writeln!(out, "  {name}: {{ args: {args}; result: {result} }};");
    }
    out.push_str("};\n");
    out
}

/// The table, `generate_handler!` and the capability name the same commands, each once; the
/// capability is the one build.rs writes (the main window only, never remote).
#[test]
fn command_names_agree_everywhere() {
    let table = command_table();
    let names: BTreeSet<String> = table.iter().map(|(n, ..)| n.clone()).collect();
    assert_eq!(names.len(), table.len(), "no command twice in commands.txt");
    for (name, ..) in &table {
        assert!(
            !name.is_empty() && name.chars().all(|c| c.is_ascii_lowercase() || c == '_'),
            "commands.txt: {name:?}"
        );
    }

    let handlers = handler_names();
    let handled: BTreeSet<String> = handlers.iter().cloned().collect();
    assert_eq!(handled.len(), handlers.len(), "no handler twice");
    let missing: Vec<&String> = names.difference(&handled).collect();
    assert!(
        missing.is_empty(),
        "in commands.txt, not in generate_handler!: {missing:?}"
    );
    let unlisted: Vec<&String> = handled.difference(&names).collect();
    assert!(
        unlisted.is_empty(),
        "in generate_handler!, not in commands.txt: {unlisted:?}"
    );

    let capability: serde_json::Value =
        serde_json::from_str(&read("src-tauri/capabilities/main.json")).unwrap();
    let allowed: Vec<String> = capability["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|p| p.as_str()?.strip_prefix("allow-"))
        .map(|p| p.replace('-', "_"))
        .collect();
    let listed: Vec<String> = table.iter().map(|(n, ..)| n.clone()).collect();
    assert_eq!(
        allowed, listed,
        "capabilities/main.json is stale: build src-tauri (build.rs writes it)"
    );
    assert_eq!(
        capability["windows"],
        serde_json::json!(["main"]),
        "the main window only"
    );
    assert!(capability.get("remote").is_none(), "never remote");
    assert!(
        read("src-tauri/build.rs").contains("\"commands.txt\""),
        "build.rs builds the manifest from the table"
    );
}

/// Each handler takes the arguments its line of the table names, camelCased as Tauri reads
/// them, with their types, and answers the table's result (`CmdResult<T>` is `T`, no result
/// `null`): a renamed parameter or a changed result fails here, not at runtime. A string union
/// of the table (`'minimize' | ...`) is a Rust enum: only its name is compared.
#[test]
fn handler_signatures_agree_with_the_table() {
    let handlers = handlers();
    let mut wrong = Vec::new();
    for (name, args, result) in command_table() {
        let Some(handler) = handlers.get(&name) else {
            wrong.push(format!(
                "{name}: no #[tauri::command] fn in src-tauri/src/commands"
            ));
            continue;
        };
        let listed = table_params(&args);
        let theirs: Vec<&String> = handler.params.keys().collect();
        let ours: Vec<&String> = listed.keys().collect();
        if theirs != ours {
            wrong.push(format!(
                "{name}: arguments {theirs:?} in the handler, {ours:?} in commands.txt"
            ));
            continue;
        }
        for (arg, ts) in &listed {
            let rust = &handler.params[arg];
            if !ts.contains('\'') && squashed(ts) != squashed(rust) {
                wrong.push(format!(
                    "{name}: {arg} is {rust} in the handler, {ts} in commands.txt"
                ));
            }
        }
        if squashed(&result) != squashed(&handler.result) {
            wrong.push(format!(
                "{name}: the handler answers {}, commands.txt says {result}",
                handler.result
            ));
        }
    }
    assert!(wrong.is_empty(), "{}", wrong.join("\n"));
}

/// The TypeScript command map is regenerated from the table; the test fails while the
/// committed file differs (commit the result; `npm run gen` writes and passes). Every type it
/// names must exist.
#[test]
fn the_typescript_command_map_is_generated_and_committed() {
    let table = command_table();
    let expected = commands_ts(&table);
    let known: BTreeSet<String> = std::fs::read_dir(repo("ui/src/lib/ipc/types"))
        .unwrap()
        .filter_map(|e| {
            let name = e.ok()?.file_name().to_string_lossy().into_owned();
            name.strip_suffix(".ts").map(str::to_string)
        })
        .collect();
    for (name, args, result) in &table {
        for word in format!("{args} {result}").split(|c: char| !c.is_ascii_alphanumeric()) {
            let is_type = word.chars().next().is_some_and(|c| c.is_ascii_uppercase());
            assert!(
                !is_type || ["Channel", "Record"].contains(&word) || known.contains(word),
                "{name}: unknown type {word}"
            );
        }
    }
    let path = repo("ui/src/lib/ipc/types/commands.ts");
    jobalert_core::export::generated::write(&path, &expected).unwrap_or_else(|e| panic!("{e}"));
}

/// Safety invariant of the session window, as far as it can be checked without a window: it
/// downloads nothing, opens no further windows, checks every navigation against its portal
/// - and is in no capability (no command of the app is reachable from there).
#[test]
fn the_session_window_downloads_nothing_and_opens_no_window() {
    let session = read("src-tauri/src/session.rs");
    for required in [
        ".on_download(|_, _| false)",
        ".on_new_window(|_, _| NewWindowResponse::Deny)",
        "Session::allowed(site, url)",
    ] {
        assert!(session.contains(required), "session.rs: {required} missing");
    }
    // The profile folder (and with it the sign-in) belongs to the portal, not a fixed name.
    assert!(session.contains("jobalert_core::session_dir(site.portal)"));

    let capability: serde_json::Value =
        serde_json::from_str(&read("src-tauri/capabilities/main.json")).unwrap();
    assert_eq!(
        capability["windows"],
        serde_json::json!(["main"]),
        "portal windows are in no capability"
    );
}

/// Every run event carries the fields the generated TypeScript promises. The end once was
/// a newtype - with `tag = "type"` such a newtype merges with the event, `event.summary`
/// was undefined and the status bar stayed on "ready" after every run.
#[test]
fn run_events_serialise_as_the_types_say() {
    use jiff::Timestamp;
    use jobalert_core::pipeline::{RunEvent, RunKindName, RunSummary};

    let now = Timestamp::now();
    let event = serde_json::to_value(RunEvent::Finished {
        summary: Box::new(RunSummary::new(RunKindName::Fetch, true, now)),
    })
    .unwrap();
    assert_eq!(event["type"], "finished");
    assert!(event["summary"].is_object(), "end without summary: {event}");
    for field in [
        "run",
        "kind",
        "outcome",
        "dryRun",
        "startedAt",
        "finishedAt",
        "scan",
        "perPortal",
        "newJobs",
        "score",
        "emptyAlerts",
    ] {
        assert!(
            event["summary"].get(field).is_some(),
            "{field} missing (null instead of missing): {event}"
        );
    }
    let ts = read("ui/src/lib/ipc/types/RunSummary.ts");
    for field in ["perPortal", "emptyAlerts", "finishedAt", "newJobs"] {
        assert!(ts.contains(field), "RunSummary.ts: {field}");
    }
    // Every run begins with its kind.
    let started = serde_json::to_value(RunEvent::Started {
        kind: RunKindName::Rescore,
    })
    .unwrap();
    assert_eq!(
        started,
        serde_json::json!({ "type": "started", "kind": "rescore" })
    );
    assert!(read("ui/src/lib/ipc/types/RunEvent.ts").contains("\"type\": \"started\""));
}
